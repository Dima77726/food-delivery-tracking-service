package com.dima.fooddelivery.tracking.domain;

import java.time.Instant;

/**
 * Точка трека курьера.
 *
 * <p><b>Почему это не строка в PostgreSQL.</b> Данные тут другой природы, чем всё остальное
 * в приложении. Курьер шлёт координату раз в несколько секунд, точек на одну доставку выходят
 * сотни, а на тысячу курьеров это поток вставок, который никто никогда не будет обновлять
 * и почти никто не станет читать старше вчерашнего дня. Cassandra придумана ровно под такой
 * профиль: запись без чтения перед ней, распределение по узлам ключом партиции и удаление
 * старого через TTL, а не через DELETE.
 *
 * <p>Цена честно оговорена: у Cassandra нет ни join, ни внешних ключей, ни транзакций между
 * партициями, а запросы разрешены только те, под которые заточен первичный ключ. Здесь
 * это ровно то, что нужно, — трек всегда читается по одной доставке и всегда с конца.
 *
 * <p>{@link Instant}, а не {@code OffsetDateTime}: время в Cassandra хранится моментом без
 * зоны — в этой таблице оно вообще зашито внутрь timeuuid, служащего ключом строки.
 * Смещение приписывается на границе API, как и в отзывах.
 */
public record CourierPosition(
        Long deliveryId,
        Long courierId,
        Instant recordedAt,
        double latitude,
        double longitude,

        /** Скорость в км/ч. Может отсутствовать: телефон отдаёт её не всегда. */
        Double speedKmh
) {
}
