package com.dima.fooddelivery.chat.domain;

/**
 * Кто пишет в чат заказа. Роль определяется не токеном, а отношением к заказу: курьер,
 * не взявший эту доставку, в её чате никто.
 */
public enum ChatRole {

    /** Клиент, чей заказ. */
    CUSTOMER,

    /** Курьер, назначенный на доставку заказа. */
    COURIER,

    /** Администратор платформы — поддержка: видит и пишет в любом чате. */
    SUPPORT
}
